# Note for developers: There are three separate loggers here.
#
#    1. The global pySAS logger named "_logger". This is used 
#       ONLY inside of pySAS. This captures the logging output
#       generated by pySAS ONLY.
#       
#       It is imported like this:
#
#           from pysas.logger import _logger
#
#       and used like this:
#
#           _logger.<log level>(Message)
#           _logger.warning('Warning level message')
#           _logger.debug('Debug level message')
#           etc...
#
#    2. An independant logger used to capture the ALL the output
#       generated by running SAS tasks. These independant loggers 
#       are generated when 'run' in MyTask is called. They have 
#       the name 'i'+<SAS task name> and are deconstructed after 
#       the subprocess call ends.
#       
#       The independant logger will direct the output to the 
#       terminal or a log file.
#    
#    3. TaskLogger is the logger used for Python code called 
#       directly from SAS tasks. If you are writing Python 
#       code using inside of SAS use this for logging errors
#       and output. Any output will be caught by the independant 
#       logger.
